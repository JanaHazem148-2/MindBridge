# ── Compiled pattern sets ─────────────────────────────────────────────────────

def _compile(patterns: List[Tuple[str, str]]):
    return [(re.compile(p, re.UNICODE | re.IGNORECASE), label) for p, label in patterns]


_HARD_COMPILED   = _compile(ARABIC_HARD_PATTERNS)
_SOFT_COMPILED   = _compile(ARABIC_SOFT_PATTERNS)
_MONITOR_COMPILED = _compile(ARABIC_MONITOR_PATTERNS)


# ── Detector ──────────────────────────────────────────────────────────────────

@dataclass
class ArabicSafetyResult:
    """Mirrors SafetyDecision structure for easy merging."""
    level: str          # "SAFE" | "MONITOR" | "SOFT_INTERVENE" | "HARD_ESCALATE"
    matched: List[str]
    label: str
    confidence: float
    resources: List[str]
    lock_session: bool


class ArabicSafetyFilter:
    """
    Layer 1 extension: Arabic/Egyptian dialect keyword filter.

    Usage:
        filter = ArabicSafetyFilter(region="EG")
        result = filter.check(user_message)

    Returns ArabicSafetyResult — merge with main SafetyOrchestrator:

        ar_result = ar_filter.check(text)
        if ar_result.level == "HARD_ESCALATE":
            # Override main decision — Arabic hard match is definitive
            return SafetyDecision(
                level=SafetyLevel.HARD_ESCALATE,
                triggered_by="arabic_keyword",
                matched=ar_result.matched,
                confidence=1.0,
                message="Crisis detected in Arabic text",
                resources=ar_result.resources,
                lock_session=True,
            )
    """

    def __init__(self, region: str = "EG"):
        self.region = region

    def is_arabic(self, text: str) -> bool:
        """Quick check: does text contain Arabic script?"""
        return bool(re.search(r"[\u0600-\u06FF]", text))

    def check(self, text: str) -> ArabicSafetyResult:
        if not self.is_arabic(text):
            return ArabicSafetyResult(
                level="SAFE", matched=[], label="not_arabic",
                confidence=1.0, resources=[], lock_session=False,
            )

        normalised = normalise_arabic(text)

        # Hard escalation
        for pattern, label in _HARD_COMPILED:
            m = pattern.search(normalised)
            if m:
                return ArabicSafetyResult(
                    level="HARD_ESCALATE",
                    matched=[m.group(0)],
                    label=label,
                    confidence=1.0,
                    resources=get_arabic_crisis_resources(self.region),
                    lock_session=True,
                )

        # Soft intervention
        triggered_soft = []
        for pattern, label in _SOFT_COMPILED:
            m = pattern.search(normalised)
            if m:
                triggered_soft.append((m.group(0), label))

        if triggered_soft:
            return ArabicSafetyResult(
                level="SOFT_INTERVENE",
                matched=[t[0] for t in triggered_soft],
                label=triggered_soft[0][1],
                confidence=0.9,
                resources=get_arabic_crisis_resources(self.region),
                lock_session=False,
            )

        # Monitor
        triggered_monitor = []
        for pattern, label in _MONITOR_COMPILED:
            m = pattern.search(normalised)
            if m:
                triggered_monitor.append((m.group(0), label))

        if triggered_monitor:
            return ArabicSafetyResult(
                level="MONITOR",
                matched=[t[0] for t in triggered_monitor],
                label=triggered_monitor[0][1],
                confidence=0.8,
                resources=[],
                lock_session=False,
            )

        return ArabicSafetyResult(
            level="SAFE", matched=[], label="clean",
            confidence=1.0, resources=[], lock_session=False,
        )


