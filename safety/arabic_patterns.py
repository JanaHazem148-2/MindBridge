# ── Text normalisation ────────────────────────────────────────────────────────

def normalise_arabic(text: str) -> str:
    """
    1. Strip diacritics (tashkeel: harakat + shadda + tanwin).
    2. Normalise alef variants → ا
    3. Normalise teh marbuta → ه  (reduces variant forms)
    4. Collapse whitespace.
    """
    # Remove tashkeel (Unicode category Mn = non-spacing mark)
    text = "".join(ch for ch in text if unicodedata.category(ch) != "Mn")
    # Alef normalisation
    text = re.sub(r"[أإآٱ]", "ا", text)
    # Teh marbuta
    text = text.replace("ة", "ه")
    # Whitespace collapse
    text = re.sub(r"\s+", " ", text).strip()
    return text


