def get_arabic_escalation_message(label: str) -> str:
    """
    Get the appropriate Arabic crisis response message by trigger label.
    Falls back to default if label not specifically handled.
    """
    for key in ARABIC_ESCALATION_MESSAGES:
        if key != "default" and key in label:
            return ARABIC_ESCALATION_MESSAGES[key]
    return ARABIC_ESCALATION_MESSAGES["default"]


